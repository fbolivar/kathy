function getRecomendaciones(cueroType, tieneCaspa) {
  return CATALOG.filter(p => {
    const matchCuero = p.cueroType.includes(cueroType);
    const matchCaspa = tieneCaspa ? p.anticaspa === true : true;
    return matchCuero && matchCaspa && p.disponible;
  }).slice(0, 4);
}

